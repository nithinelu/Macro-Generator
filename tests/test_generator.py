class ProfileTests(unittest.TestCase):
    def test_round_trip(self):
        t = BY_ID["quick_dial"]
        values = t.defaults() | {"panelName": "Dial Me"}
        with tempfile.TemporaryDirectory() as d:
            path = Path(d) / "p.json"
            save_profile(path, t, "My_Dial", values)
            t2, name, loaded = load_profile(path)
        self.assertEqual((t2.id, name, loaded["panelName"]), ("quick_dial", "My_Dial", "Dial Me"))

    def test_profile_with_utf8_bom_loads(self):
        with tempfile.TemporaryDirectory() as d:
            path = Path(d) / "p.json"
            path.write_text('{"template": "quick_dial", "macro_name": "Q", "values": {}}', encoding="utf-8-sig")
            self.assertEqual(load_profile(path)[1], "Q")

    def test_unknown_template_is_rejected(self):
        with tempfile.TemporaryDirectory() as d:
            path = Path(d) / "p.json"
            path.write_text('{"template": "nope"}', encoding="utf-8")
            with self.assertRaises(ValueError):
                load_profile(path)


class CliTests(unittest.TestCase):
    def run_cli(self, *argv):
        import contextlib
        import io
        import main
        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            code = main.main(list(argv))
        return code, out.getvalue(), err.getvalue()

    def test_init_then_render(self):
        with tempfile.TemporaryDirectory() as d:
            profile, out = str(Path(d) / "p.json"), str(Path(d) / "m.js")
            self.assertEqual(self.run_cli("init", "quick_dial", profile)[0], 0)
            self.assertEqual(self.run_cli("render", profile, "-o", out)[0], 0)
            self.assertIn("panel_quick_dial", Path(out).read_text(encoding="utf-8"))

    def test_invalid_profile_reports_problems_not_a_traceback(self):
        with tempfile.TemporaryDirectory() as d:
            path = Path(d) / "bad.json"
            path.write_text('{"template":"quick_dial","macro_name":"bad name","values":{"entries":[]}}', encoding="utf-8")
            code, _, err = self.run_cli("render", str(path))
        self.assertEqual(code, 1)
        self.assertIn("Macro name", err)
        self.assertIn("Speed dials", err)

    def test_missing_and_malformed_profiles_exit_cleanly(self):
        with tempfile.TemporaryDirectory() as d:
            self.assertEqual(self.run_cli("render", str(Path(d) / "nope.json"))[0], 2)
            broken = Path(d) / "broken.json"
            broken.write_text("{not json", encoding="utf-8")
            code, _, err = self.run_cli("render", str(broken))
            self.assertEqual(code, 2)
            self.assertTrue(err.startswith("Error:"))

    def test_unknown_template_in_init(self):
        self.assertEqual(self.run_cli("init", "nope", "x.json")[0], 2)


class DeviceTests(unittest.TestCase):
    def test_save_command_xml_escapes_code_and_has_body(self):
        xml = device._command_xml(["Macros", "Macro", "Save"], {"Name": "M", "Overwrite": "True"}, "if (a < b && c > d) {}")
        root = ET.fromstring(xml)
        save = root.find("Macros/Macro/Save")
        self.assertEqual(save.find("Name").text, "M")
        self.assertEqual(save.find("body").text, "if (a < b && c > d) {}")

    def test_find_error(self):
        self.assertEqual(device.find_error('<Command><MacroSaveResult status="OK"/></Command>'), "")
        self.assertEqual(
            device.find_error('<Command><MacroSaveResult status="Error"><Reason>No way</Reason></MacroSaveResult></Command>'),
            "No way")
        self.assertEqual(device.find_error("<Configuration><Error>Bad</Error></Configuration>"), "Bad")

    def _fake_session(self, replies):
        session = mock.Mock()
        session.post.side_effect = replies
        return session

    @staticmethod
    def _reply(status=200, text="<Command/>"):
        return mock.Mock(status_code=status, text=text)

    def test_push_runs_all_steps_in_order(self):
        session = self._fake_session([self._reply() for _ in range(4)])
        res = device.push_macro("10.0.0.5", "admin", "pw", "M", "code", session=session)
        self.assertTrue(res.ok, res.error)
        sent = [ET.fromstring(c.kwargs["data"]) for c in session.post.call_args_list]
        self.assertIsNotNone(sent[0].find("Macros/Mode"))
        self.assertIsNotNone(sent[1].find("Macros/Macro/Save"))
        self.assertIsNotNone(sent[2].find("Macros/Macro/Activate"))
        self.assertIsNotNone(sent[3].find("Macros/Runtime/Restart"))
        self.assertEqual(session.post.call_args_list[0].args[0], "https://10.0.0.5/putxml")

    def test_push_reports_bad_login(self):
        session = self._fake_session([self._reply(401)])
        res = device.push_macro("10.0.0.5", "admin", "bad", "M", "code", session=session)
        self.assertFalse(res.ok)
        self.assertIn("login rejected", res.error)

    def test_push_stops_on_device_error(self):
        err = '<Command><MacroSaveResult status="Error"><Reason>Too big</Reason></MacroSaveResult></Command>'
        session = self._fake_session([self._reply(), self._reply(text=err)])
        res = device.push_macro("h", "u", "p", "M", "code", session=session)
        self.assertFalse(res.ok)
        self.assertIn("Too big", res.error)
        self.assertEqual(session.post.call_count, 2)


