def config_from_js(js: str) -> dict:
    """Pull the generated `const config = {...};` back out and parse it as JSON."""
    start = js.index("const config = ") + len("const config = ")
    end = js.index("\n};", start) + 2
    return json.loads(js[start:end])


class TemplateTests(unittest.TestCase):
    def test_every_template_renders_with_defaults(self):
        for t in TEMPLATES:
            with self.subTest(t.id):
                js, errors = generate(t, t.default_macro_name, t.defaults())
                self.assertEqual(errors, [])
                self.assertTrue(js.lstrip().startswith("// Generated by Macro Generator"))
                self.assertIn("import xapi from 'xapi';", js)
                self.assertNotIn("/*__CONFIG__*/", js)
                self.assertNotIn("__TAG__", js)
                self.assertIsInstance(config_from_js(js), dict)

    def test_values_are_typed_in_output(self):
        t = BY_ID["room_release"]
        raw = t.defaults() | {"releaseDelaySeconds": "120", "usePeopleCount": "false"}
        cfg = config_from_js(generate(t, "X", raw)[0])
        self.assertEqual(cfg["releaseDelaySeconds"], 120)
        self.assertIs(cfg["usePeopleCount"], False)

    def test_climate_limits_become_numbers(self):
        t = BY_ID["room_control"]
        cfg = config_from_js(generate(t, "X", t.defaults())[0])
        self.assertEqual(cfg["climate"][0]["minTemp"], 18)
        self.assertEqual(cfg["climate"][0]["maxTemp"], 30)

    def test_quotes_and_unicode_survive(self):
        t = BY_ID["quick_dial"]
        raw = t.defaults() | {"entries": [{"label": 'Say "hi" — café', "number": "a@b.com"}]}
        cfg = config_from_js(generate(t, "X", raw)[0])
        self.assertEqual(cfg["entries"][0]["label"], 'Say "hi" — café')

    def test_lines_field_splits_headers(self):
        t = BY_ID["room_control"]
        raw = t.defaults() | {"headers": "Authorization: Bearer abc\n\n X-Site: 1 \n"}
        cfg = config_from_js(generate(t, "X", raw)[0])
        self.assertEqual(cfg["headers"], ["Authorization: Bearer abc", "X-Site: 1"])

    def test_empty_table_rows_are_dropped(self):
        t = BY_ID["room_control"]
        raw = t.defaults() | {"blinds": [{"label": "", "upUrl": "", "stopUrl": "", "downUrl": ""}]}
        self.assertEqual(config_from_js(generate(t, "X", raw)[0])["blinds"], [])


