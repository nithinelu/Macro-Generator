"""Smoke-tests the Tk GUI without a mainloop. Skipped when Tk can't open a display."""
import sys
import tempfile
import tkinter as tk
import unittest
from pathlib import Path
from unittest import mock

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))


def tk_available() -> bool:
    try:
        root = tk.Tk()
        root.destroy()
        return True
    except tk.TclError:
        return False


@unittest.skipUnless(tk_available(), "no display for Tk")
class GuiSmoke(unittest.TestCase):
    def setUp(self):
        from macro_generator import gui
        self.gui = gui
        self.settings = tempfile.NamedTemporaryFile(suffix=".json", delete=False)
        self.settings.close()
        patcher = mock.patch.object(gui, "SETTINGS_FILE", Path(self.settings.name))
        patcher.start()
        self.addCleanup(patcher.stop)
        self.app = gui.App()
        self.addCleanup(self.app.destroy)
        self.app.update()

    def test_every_template_previews_without_errors(self):
        from macro_generator.templates import TEMPLATES
        for i, t in enumerate(TEMPLATES):
            with self.subTest(t.id):
                self.app.select_template(i)
                self.app.update()
                self.assertTrue(self.app.current_js.startswith("// Generated by Macro Generator"), self.app.status.cget("text"))

    def test_editing_a_field_updates_the_output(self):
        self.app.select_template(0)
        self.app.vars["releaseDelaySeconds"].set("123")
        self.app.refresh()
        self.assertIn('"releaseDelaySeconds": 123', self.app.current_js)

    def test_invalid_input_blocks_output_and_explains(self):
        self.app.select_template(0)
        self.app.vars["releaseDelaySeconds"].set("x")
        self.app.refresh()
        self.assertEqual(self.app.current_js, "")
        self.assertIn("Grace period", self.app.status.cget("text"))

    def test_table_rows_flow_into_output(self):
        idx = [t.id for t in __import__("macro_generator.templates", fromlist=["TEMPLATES"]).TEMPLATES].index("quick_dial")
        self.app.select_template(idx)
        table = self.app.widgets["entries"]
        table.rows.append({"label": "Reception", "number": "reception@example.com"})
        table._redraw()
        self.app.refresh()
        self.assertIn("Reception", self.app.current_js)
        table.tree.selection_set("0")
        table.delete()
        self.app.refresh()
        self.assertNotIn("IT Helpdesk", self.app.current_js)

    def test_profile_round_trip_through_gui(self):
        from macro_generator.profile import save_profile, load_profile
        self.app.select_template(1)
        self.app.vars["panelName"].set("Boardroom Controls")
        self.app.macro_name.set("Boardroom_Ctl")
        with tempfile.TemporaryDirectory() as d:
            path = Path(d) / "p.json"
            save_profile(path, self.app.template, self.app.macro_name.get(), self.app.get_values())
            template, name, values = load_profile(path)
        self.app.select_template(0)
        self.app.select_template(1, values, name)
        self.assertEqual(self.app.vars["panelName"].get(), "Boardroom Controls")
        self.assertEqual(self.app.macro_name.get(), "Boardroom_Ctl")
        self.assertEqual(len(self.app.widgets["lights"].rows), 1)

    def test_lines_field_round_trips(self):
        self.app.select_template(1)
        self.app.widgets["headers"].insert("1.0", "Authorization: Bearer abc")
        self.app.refresh()
        self.assertIn("Authorization: Bearer abc", self.app.current_js)


if __name__ == "__main__":
    unittest.main()
