"""Template model: field definitions, value coercion/validation and JS rendering."""
from __future__ import annotations

import copy
import json
import re
from dataclasses import dataclass, field
from typing import Any, Callable

GENERATED_BANNER = "// Generated by Macro Generator - template: {name}\n"
CONFIG_MARKER = "/*__CONFIG__*/"
MACRO_NAME_RE = re.compile(r"^[A-Za-z0-9_\-]{1,64}$")


@dataclass
class Column:
    key: str
    label: str
    default: str = ""
    width: int = 220


@dataclass
class Field:
    key: str
    label: str
    kind: str                      # str | int | bool | choice | lines | table
    default: Any = None
    help: str = ""
    choices: list[str] = field(default_factory=list)
    columns: list[Column] = field(default_factory=list)
    required: bool = False
    min: int | None = None
    max: int | None = None


@dataclass
class Template:
    id: str
    name: str
    description: str
    fields: list[Field]
    body: str                      # JS with CONFIG_MARKER where `const config = ...;` goes
    default_macro_name: str
    prerequisites: list[str] = field(default_factory=list)
    extra_validate: Callable[[dict[str, Any]], list[str]] | None = None
    post_render: Callable[[dict[str, Any]], dict[str, Any]] | None = None   # final type fix-ups before JS output

    def defaults(self) -> dict[str, Any]:
        out: dict[str, Any] = {}
        for f in self.fields:
            if f.kind == "table":
                out[f.key] = [{c.key: c.default for c in f.columns}]
            else:
                out[f.key] = f.default
        return out


def coerce(template: Template, raw: dict[str, Any]) -> dict[str, Any]:
    """Turn GUI/profile values into typed config values (ints, bools, string lists, row dicts)."""
    values: dict[str, Any] = {}
    for f in template.fields:
        v = raw.get(f.key, f.default)
        if f.kind == "int":
            try:
                v = int(str(v).strip())
            except (TypeError, ValueError):
                v = None
        elif f.kind == "bool":
            v = v if isinstance(v, bool) else str(v).strip().lower() in ("1", "true", "yes", "on")
        elif f.kind == "lines":
            if isinstance(v, str):
                v = [ln.strip() for ln in v.splitlines() if ln.strip()]
            else:
                v = [str(x).strip() for x in (v or []) if str(x).strip()]
        elif f.kind == "table":
            rows = []
            for row in v or []:
                clean = {c.key: str(row.get(c.key, "")).strip() for c in f.columns}
                if any(clean.values()):
                    rows.append(clean)
            v = rows
        else:
            v = "" if v is None else str(v).strip()
        values[f.key] = v
    return values


def validate(template: Template, values: dict[str, Any]) -> list[str]:
    """`values` must already be coerced."""
    errors: list[str] = []
    for f in template.fields:
        v = values[f.key]
        if f.kind == "int":
            if v is None:
                errors.append(f"{f.label}: enter a whole number.")
                continue
            if f.min is not None and v < f.min:
                errors.append(f"{f.label}: must be at least {f.min}.")
            if f.max is not None and v > f.max:
                errors.append(f"{f.label}: must be at most {f.max}.")
        elif f.kind in ("str", "choice") and f.required and not v:
            errors.append(f"{f.label}: required.")
        elif f.kind == "choice" and v and v not in f.choices:
            errors.append(f"{f.label}: '{v}' is not one of {', '.join(f.choices)}.")
        elif f.kind == "table":
            if f.required and not v:
                errors.append(f"{f.label}: add at least one row.")
            for i, row in enumerate(v, start=1):
                for c in f.columns:
                    val = row[c.key]
                    if c.key.lower().endswith("url") and val and not re.match(r"^https?://\S+$", val):
                        errors.append(f"{f.label} row {i}: {c.label} must start with http:// or https://")
                    if c.key == "label" and not val:
                        errors.append(f"{f.label} row {i}: {c.label} is required.")
        if f.kind == "str" and f.key.lower().endswith("url") and v and not re.match(r"^https?://\S+$", v):
            errors.append(f"{f.label}: must start with http:// or https://")
    if template.extra_validate and not errors:
        errors.extend(template.extra_validate(values))
    return errors


def validate_macro_name(name: str) -> list[str]:
    if MACRO_NAME_RE.match(name or ""):
        return []
    return ["Macro name: use 1-64 letters, digits, '_' or '-' (no spaces)."]


def render(template: Template, values: dict[str, Any]) -> str:
    """Render JS for already-coerced, validated values."""
    if template.post_render:
        values = template.post_render(copy.deepcopy(values))
    config_js = "const config = " + json.dumps(values, indent=2, ensure_ascii=False) + ";"
    return GENERATED_BANNER.format(name=template.name) + template.body.replace(CONFIG_MARKER, config_js)
